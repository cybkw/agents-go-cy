    #[test]
    fn preserves_existing_hooks_unknown_settings_and_is_idempotent() {
        let root = project();
        fs::create_dir(root.join(".claude")).unwrap();
        fs::write(root.join(".gitignore"), "# custom\r\n/custom\r\n").unwrap();
        let existing = json!({
            "permissions": {"allow": ["Bash(cargo test:*)"]},
            "futureSetting": {"enabled": true},
            "hooks": {
                "SessionStart": [{"hooks": [{"type":"command","command":"echo keep"}]}],
                "Stop": [{"matcher":"", "futureGroup": true, "hooks": [
                    {"type":"command","command":"echo user hook","futureField":[1,2]}
                ]}]
            }
        });
        fs::write(
            root.join(".claude/settings.local.json"),
            json_bytes(&existing).unwrap(),
        )
        .unwrap();

        assert!(!install(&root).unwrap().is_empty());
        let installed: Value =
            serde_json::from_slice(&fs::read(root.join(".claude/settings.local.json")).unwrap())
                .unwrap();
        assert_eq!(installed["permissions"], existing["permissions"]);
        assert_eq!(installed["futureSetting"], existing["futureSetting"]);
        assert_eq!(
            installed["hooks"]["SessionStart"],
            existing["hooks"]["SessionStart"]
        );
        assert_eq!(installed["hooks"]["Stop"][0], existing["hooks"]["Stop"][0]);
        assert_eq!(installed["hooks"]["Stop"].as_array().unwrap().len(), 2);
        assert!(install(&root).unwrap().is_empty());
        assert!(fs::read_to_string(root.join(".gitignore"))
            .unwrap()
            .starts_with("# custom\r\n/custom\r\n"));
        assert_eq!(
            fs::read(root.join(".agents-go/project.json")).unwrap(),
            b"{\"version\":1}\n"
        );
    }

