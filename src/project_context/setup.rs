use serde_json::{json, Value};

const SKILL: &str = include_str!("assets/project-resume/SKILL.md");
const OPENAI_POLICY: &str = include_str!("assets/project-resume/agents/openai.yaml");
const GENERATED_SKILL: &str = "<!-- Generated by Agents Go project context v1. -->";
const HOOK_MARKER: &str = "Agents Go project context v1: ";
#[cfg(test)]
static TEMP_ID: AtomicU64 = AtomicU64::new(0);

struct PendingFile {
    path: PathBuf,
    original: Option<Vec<u8>>,
    content: Vec<u8>,
}

/// Install project-local capture hooks and explicitly invoked recovery skills.
/// All files are checked before writing; the enabling marker is written last.
pub(crate) fn enable(
    root: &Path,
    executable: &Path,
    agents: &[String],
) -> Result<Vec<PathBuf>, String> {
    if !root.is_absolute() || !root.is_dir() {
        return Err("project root must be an existing absolute directory".into());
    }
    if !executable.is_absolute() || !executable.is_file() {
        return Err("capture executable must be an existing absolute file".into());
    }
    #[cfg(windows)]
    if !executable
        .extension()
        .is_some_and(|ext| ext.eq_ignore_ascii_case("exe"))
    {
        return Err("capture executable must be a Windows .exe, not a shell shim".into());
    }
    let root_text = unicode_path(root)?;
    let executable_text = unicode_path(executable)?;
    if agents.is_empty()
        || agents
            .iter()
            .any(|agent| !matches!(agent.as_str(), "codex" | "claude"))
    {
        return Err("select at least one supported agent: codex, claude".into());
    }

    let mut pending = Vec::new();
    let mut ignore_paths = vec!["/.agents-go/"];
    for agent in ["codex", "claude"] {
        if !agents.iter().any(|requested| requested == agent) {
            continue;
        }
        let (settings, skill_dir) = match agent {
            "codex" => (".codex/hooks.json", ".agents/skills/project-resume"),
            _ => (
                ".claude/settings.local.json",
                ".claude/skills/project-resume",
            ),
        };
        let path = root.join(settings);
        let original = read_checked(root, &path)?;
        let mut value = parse_object(&path, original.as_deref())?;
        merge_hooks(&mut value, agent, executable_text, root_text, &path)?;
        pending.push(PendingFile {
            path,
            original,
            content: json_bytes(&value)?,
        });

        let skill_path = root.join(skill_dir).join("SKILL.md");
        let original = read_checked(root, &skill_path)?;
        if original
            .as_ref()
            .is_some_and(|bytes| !String::from_utf8_lossy(bytes).contains(GENERATED_SKILL))
        {
            return Err(format!(
                "existing skill is not managed by Agents Go; left unchanged: {}",
                skill_path.display()
            ));
        }
        let invocation = if cfg!(windows) {
            format!("& {}", powershell_quote(executable_text))
        } else {
            posix_quote(executable_text)
        };
        let mut skill = SKILL.replace("HERDR_COMMAND", &invocation);
        if agent == "claude" {
            skill = skill.replacen(
                "name: project-resume\n",
                "name: project-resume\ndisable-model-invocation: true\n",
                1,
            );
        }
        pending.push(PendingFile {
            path: skill_path,
            original,
            content: skill.into_bytes(),
        });

        if agent == "codex" {
            let path = root.join(skill_dir).join("agents/openai.yaml");
            let original = read_checked(root, &path)?;
            if original
                .as_deref()
                .is_some_and(|bytes| bytes != OPENAI_POLICY.as_bytes())
            {
                return Err(format!(
                    "existing skill policy differs from Agents Go; left unchanged: {}",
                    path.display()
                ));
            }
            pending.push(PendingFile {
                path,
                original,
                content: OPENAI_POLICY.as_bytes().to_vec(),
            });
            ignore_paths.extend(["/.codex/hooks.json", "/.agents/skills/project-resume/"]);
        } else {
            ignore_paths.extend([
                "/.claude/settings.local.json",
                "/.claude/skills/project-resume/",
            ]);
        }
    }

    let ignore_path = root.join(".gitignore");
    let ignore_original = read_checked(root, &ignore_path)?;
    let ignore = match &ignore_original {
        Some(bytes) => std::str::from_utf8(bytes)
            .map_err(|error| format!("cannot read {} as UTF-8: {error}", ignore_path.display()))?,
        None => "",
    };
    pending.push(PendingFile {
        path: ignore_path,
        content: append_ignore_paths(ignore, &ignore_paths).into_bytes(),
        original: ignore_original,
    });

    let marker_path = root.join(".agents-go/project.json");
    let marker_original = read_checked(root, &marker_path)?;
    if marker_original.is_some() {
        let marker = parse_object(&marker_path, marker_original.as_deref())?;
        if marker["version"] != json!(1) {
            return Err(format!(
                "unsupported project context marker; left unchanged: {}",
                marker_path.display()
            ));
        }
    }
    pending.push(PendingFile {
        path: marker_path,
        content: marker_original
            .clone()
            .unwrap_or_else(|| b"{\"version\":1}\n".to_vec()),
        original: marker_original,
    });

    let mut changed = Vec::new();
    for file in pending {
        if file.original.as_deref() == Some(file.content.as_slice()) {
            continue;
        }
        let result = (|| {
            // Reject changes made since preflight instead of replacing newer settings.
            if read_checked(root, &file.path)? != file.original {
                return Err(format!(
                    "file changed during setup: {}",
                    file.path.display()
                ));
            }
            write_atomic(&file.path, &file.content)
        })();
        if let Err(error) = result {
            let completed = changed
                .iter()
                .map(|path: &PathBuf| path.display().to_string())
                .collect::<Vec<_>>()
                .join(", ");
            return Err(format!(
                "{error}; setup stopped without rollback; already changed: {}",
                if completed.is_empty() {
                    "none"
                } else {
                    &completed
                }
            ));
        }
        changed.push(file.path);
    }
    Ok(changed)
}

fn unicode_path(path: &Path) -> Result<&str, String> {
    path.to_str()
        .filter(|text| !text.chars().any(char::is_control))
        .ok_or_else(|| {
            format!(
                "path must be Unicode without control characters: {}",
                path.display()
            )
        })
}

fn read_checked(root: &Path, path: &Path) -> Result<Option<Vec<u8>>, String> {
    let relative = path
        .strip_prefix(root)
        .map_err(|_| "setup path escapes project root")?;
    let mut checked = root.to_path_buf();
    for component in relative.components() {
        checked.push(component);
        let metadata = match fs::symlink_metadata(&checked) {
            Ok(metadata) => metadata,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
            Err(error) => return Err(format!("cannot inspect {}: {error}", checked.display())),
        };
        if is_redirect(&metadata) {
            return Err(format!(
                "setup does not follow links: {}",
                checked.display()
            ));
        }
        if checked != path && !metadata.is_dir() {
            return Err(format!(
                "setup parent is not a directory: {}",
                checked.display()
            ));
        }
        if checked == path {
            if !metadata.is_file() || metadata.permissions().readonly() {
                return Err(format!(
                    "setup target is not a writable file: {}",
                    path.display()
                ));
            }
            crate::integration::config_file::check_config_target(path)
                .map_err(|error| format!("cannot update {}: {error}", path.display()))?;
            return fs::read(path)
                .map(Some)
                .map_err(|error| format!("cannot read {}: {error}", path.display()));
        }
    }
    Ok(None)
}

fn is_redirect(metadata: &fs::Metadata) -> bool {
    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;
        metadata.file_attributes() & 0x400 != 0
    }
    #[cfg(not(windows))]
    {
        metadata.file_type().is_symlink()
    }
}

fn parse_object(path: &Path, bytes: Option<&[u8]>) -> Result<Value, String> {
    let Some(bytes) = bytes else {
        return Ok(json!({}));
    };
    let bytes = bytes.strip_prefix(b"\xef\xbb\xbf").unwrap_or(bytes);
    let value: Value = serde_json::from_slice(bytes).map_err(|error| {
        format!(
            "invalid JSON in {}; left unchanged: {error}",
            path.display()
        )
    })?;
    if !value.is_object() {
        return Err(format!(
            "expected a JSON object in {}; left unchanged",
            path.display()
        ));
    }
    Ok(value)
}

fn merge_hooks(
    settings: &mut Value,
    agent: &str,
    executable: &str,
    root: &str,
    path: &Path,
) -> Result<(), String> {
    let invalid = || {
        format!(
            "invalid hooks structure in {}; left unchanged",
            path.display()
        )
    };
    let hooks = settings
        .as_object_mut()
        .ok_or_else(invalid)?
        .entry("hooks")
        .or_insert_with(|| json!({}))
        .as_object_mut()
        .ok_or_else(invalid)?;
    let handler = capture_handler(agent, executable, root);
    let marker = format!("{HOOK_MARKER}{agent}");
    for event in ["UserPromptSubmit", "Stop"] {
        let groups = hooks.entry(event).or_insert_with(|| json!([]));
        let groups = groups.as_array_mut().ok_or_else(invalid)?;
        let mut installed = false;
        for group in groups.iter_mut() {
            let handlers = group
                .as_object_mut()
                .and_then(|group| group.get_mut("hooks"))
                .and_then(Value::as_array_mut)
                .ok_or_else(invalid)?;
            for existing in handlers {
                if !existing.is_object() {
                    return Err(invalid());
                }
                if existing.get("statusMessage").and_then(Value::as_str) == Some(&marker) {
                    if installed {
                        return Err(format!(
                            "duplicate managed capture hook in {}; left unchanged",
                            path.display()
                        ));
                    }
                    // Keep unknown fields even on our own handler.
                    let existing = existing.as_object_mut().ok_or_else(invalid)?;
                    for (key, value) in handler.as_object().expect("handler object") {
                        existing.insert(key.clone(), value.clone());
                    }
                    installed = true;
                }
            }
        }
        if !installed {
            groups.push(json!({"hooks": [handler.clone()]}));
        }
    }
    Ok(())
}

fn capture_handler(agent: &str, executable: &str, root: &str) -> Value {
    let args = ["context", "capture", "--agent", agent, "--project", root];
    let marker = format!("{HOOK_MARKER}{agent}");
    if agent == "claude" {
        // Claude's exec form preserves stdin and argv without a platform shell.
        json!({
            "type": "command",
            "command": executable,
            "args": args,
            "statusMessage": marker,
            "timeout": 30
        })
    } else {
        let command = std::iter::once(executable)
            .chain(args)
            .map(posix_quote)
            .collect::<Vec<_>>()
            .join(" ");
        json!({
            "type": "command",
            "command": command,
            "commandWindows": windows_command(executable, &args),
            "statusMessage": marker,
            "timeout": 30
        })
    }
}

fn posix_quote(argument: &str) -> String {
    format!("'{}'", argument.replace('\'', "'\"'\"'"))
}

fn powershell_quote(argument: &str) -> String {
    format!("'{}'", argument.replace('\'', "''"))
}

/// Quote for a Win32 process argv, not for a shell. Always quoting also handles
/// an empty argument and doubles trailing backslashes before the closing quote.
fn windows_quote(argument: &str) -> String {
    let mut quoted = String::from("\"");
    let mut slashes = 0;
    for character in argument.chars() {
        if character == '\\' {
            slashes += 1;
        } else {
            if character == '"' {
                quoted.extend(std::iter::repeat_n('\\', slashes * 2 + 1));
            } else {
                quoted.extend(std::iter::repeat_n('\\', slashes));
            }
            slashes = 0;
            quoted.push(character);
        }
    }
    quoted.extend(std::iter::repeat_n('\\', slashes * 2));
    quoted.push('"');
    quoted
}

fn windows_command(executable: &str, args: &[&str]) -> String {
    let arguments = args
        .iter()
        .map(|arg| windows_quote(arg))
        .collect::<Vec<_>>()
        .join(" ");
    // Windows PowerShell's native pipeline may transcode UTF-8 input. Copy raw
    // stdin bytes directly into the child instead, including multiline prompts.
    let script = format!(
        "$ErrorActionPreference='Stop'; \
         $start=New-Object System.Diagnostics.ProcessStartInfo; \
         $start.FileName={}; $start.Arguments={}; \
         $start.UseShellExecute=$false; $start.RedirectStandardInput=$true; \
         $start.CreateNoWindow=$true; \
         $child=[System.Diagnostics.Process]::Start($start); \
         [Console]::OpenStandardInput().CopyTo($child.StandardInput.BaseStream); \
         $child.StandardInput.Close(); $child.WaitForExit(); exit $child.ExitCode",
        powershell_quote(executable),
        powershell_quote(&arguments),
    );
    let utf16 = script
        .encode_utf16()
        .flat_map(u16::to_le_bytes)
        .collect::<Vec<_>>();
    let encoded = base64::engine::general_purpose::STANDARD.encode(utf16);
    format!("powershell.exe -NoLogo -NoProfile -NonInteractive -EncodedCommand {encoded}")
}

fn json_bytes(value: &Value) -> Result<Vec<u8>, String> {
    let mut bytes = serde_json::to_vec_pretty(value).map_err(|error| error.to_string())?;
    bytes.push(b'\n');
    Ok(bytes)
}

fn append_ignore_paths(original: &str, paths: &[&str]) -> String {
    let newline = if original.contains("\r\n") {
        "\r\n"
    } else {
        "\n"
    };
    let mut result = original.to_owned();
    for path in paths {
        if original.lines().any(|line| line == *path) {
            continue;
        }
        if !result.is_empty() && !result.ends_with('\n') {
            result.push_str(newline);
        }
        result.push_str(path);
        result.push_str(newline);
    }
    result
}

fn write_atomic(path: &Path, content: &[u8]) -> Result<(), String> {
    let parent = path
        .parent()
        .ok_or_else(|| "setup target has no parent".to_owned())?;
    fs::create_dir_all(parent)
        .map_err(|error| format!("cannot create {}: {error}", parent.display()))?;
    // Reuse the integration writer: it preserves mode/ACL/security attributes
    // and protects existing Windows files with the repository's recovery path.
    crate::integration::config_file::write_config(path, content)
        .map_err(|error| format!("cannot save {}: {error}", path.display()))
}

