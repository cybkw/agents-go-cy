    #[cfg(windows)]
    #[test]
    fn windows_hook_transports_unicode_arguments_and_raw_stdin() {
        use std::process::{Command, Stdio};

        let root = project().join("中文 空格 ' $ ` &");
        fs::create_dir(&root).unwrap();
        let executable = root.join("capture probe.exe");
        fs::copy(std::env::current_exe().unwrap(), &executable).unwrap();
        let output = root.join("stdin.json");
        let argv = root.join("argv.json");
        let payload = "{\"prompt\":\"中文 😀 \\\"\\r\\n 第二行\"}\r\n".as_bytes();
        let tricky = "中文 空格 ' $ ` & \\\"quoted\\\" trailing\\";
        let args = ["capture_probe_process", "--nocapture", "--", tricky];
        let generated = windows_command(executable.to_str().unwrap(), &args);
        let mut parts = generated.split_whitespace();
        let program = parts.next().unwrap();
        let mut child = Command::new(program)
            .args(parts)
            .env("HERDR_CONTEXT_SETUP_PROBE", &output)
            .env("HERDR_CONTEXT_SETUP_ARGV", &argv)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .unwrap();
        child.stdin.take().unwrap().write_all(payload).unwrap();
        let result = child.wait_with_output().unwrap();
        assert!(
            result.status.success(),
            "{}",
            String::from_utf8_lossy(&result.stderr)
        );
        assert_eq!(fs::read(&output).unwrap(), payload);
        let captured_args: Vec<String> = serde_json::from_slice(&fs::read(&argv).unwrap()).unwrap();
        assert_eq!(&captured_args[1..], args);
    }
